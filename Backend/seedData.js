// Older seeded records of the five examination workflows had inconsistent stages; those types
// are now generated by the engine (workflows/seed.js). Only legacy request types are kept here.
const LEGACY_SEED_PROCESSES = SEED_PROCESSES.filter((p) => !WORKFLOW_TYPES.includes(p.type));

const buildSeedNotifications = (workflowSeeds) => {
  const events = [];
  for (const proc of workflowSeeds) {
    if (['Approved', 'Declined'].includes(proc.status)) continue;
    if (proc.status === 'Returned for Correction') {
      events.push(engine.studentNotice(proc, { type: 'CORRECTION', priority: 'urgent', title: `Returned for correction: ${proc.trackingNumber}`, message: `${proc.returnDetails.returnedByRole} returned your application. Required action: ${proc.returnDetails.reason}` }));
      continue;
    }
    const stage = proc.stages[proc.currentStageIndex];
    if (stage) events.push({ ...engine.stageEntryNotice(proc, stage, null), createdAt: proc.updatedAt });
  }
  return events;
};

const ensureCoreUsers = async () => {
  const updated = [];
  try {
    if (mongoose.connection.readyState !== 1) return updated;
    const User = require('./models/User');
    for (const u of SEED_USERS) {
      const email = String(u.email || '').toLowerCase().trim();
      const existing = await User.findOne({ email });
      if (existing) {
        let changed = false;
        if (existing.role !== u.role || existing.roleKey !== (u.roleKey || u.role)) {
          existing.role = u.role;
          existing.roleKey = u.roleKey || u.role;
          changed = true;
        }
        if (existing.designation !== u.designation) {
          existing.designation = u.designation;
          changed = true;
        }
        if (existing.department !== u.department) {
          existing.department = u.department;
          changed = true;
        }
        if (existing.name !== u.name) {
          existing.name = u.name;
          changed = true;
        }
        if (changed) {
          await existing.save();
          console.log(` Restored core user role for ${email} -> ${u.role} (${u.designation})`);
          updated.push({ email, role: u.role, status: 'restored' });
        } else {
          updated.push({ email, role: u.role, status: 'verified' });
        }
      } else {
        await User.create({
          ...u,
          email,
          password: hashPassword(u.password || '123456'),
        });
        console.log(` Created missing core user ${email} (${u.role})`);
        updated.push({ email, role: u.role, status: 'created' });
      }
    }
  } catch (error) {
    console.warn(' ensureCoreUsers note:', error.message);
  }
  return updated;
};

// Demo accounts all share a well-known password, so they are never created in production unless asked for.
const demoSeedingEnabled = () => (process.env.SEED_DEMO_DATA ? process.env.SEED_DEMO_DATA === 'true' : process.env.NODE_ENV !== 'production');

const seedDatabase = async () => {
  await ensureCoreUsers();
  if (!demoSeedingEnabled()) {
    console.log(' Demo data seeding is disabled (set SEED_DEMO_DATA=true to enable).');
    return;
  }
  try {
    const users = SEED_USERS.map((u) => ({ ...u, password: hashPassword(u.password) }));
    const workflowSeeds = buildWorkflowSeeds();
    const processes = [...LEGACY_SEED_PROCESSES, ...workflowSeeds];

    // Repair records left in MongoDB by the earlier seed (same tracking number, different stages).
    if (mongoose.connection.readyState === 1) {
      for (const seed of workflowSeeds) {
        const existing = await ProcessRequest.findOne({ trackingNumber: seed.trackingNumber }, 'stages.stageKey');
        const keys = (doc) => (doc.stages || []).map((s) => s.stageKey).join('|');
        if (existing && keys(existing) !== keys(seed)) {
          await ProcessRequest.deleteOne({ _id: existing._id });
          console.log(` Repaired outdated seed record ${seed.trackingNumber}.`);
        }
      }
    }

    await store.initialise({ seedUsers: users, seedProcesses: processes, seedNotifications: [] });
    console.log(` Storage ready (${store.connected() ? 'MongoDB' : 'in-memory'}): ${processes.length} seed applications available.`);
  } catch (error) {
    console.warn(' Seed database note:', error.message);
  }
};

module.exports = { SEED_USERS, SEED_PROCESSES: LEGACY_SEED_PROCESSES, seedDatabase, ensureCoreUsers };
